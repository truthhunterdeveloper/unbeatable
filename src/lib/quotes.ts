/** Deterministic "quote of the day" so it stays the same all day, different per area. */
export function dailyIndex(area: QuoteArea, date: string): number {
  let h = 0;
  for (const ch of area + date) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h % QUOTES[area].length;
}

